# Arithmetic operators
a = 10
b = 3
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor division:", a // b)
print("Remainder:", a % b)
print("Power:", a ** b)

# Comparison operators
print("Equal:", a == b)
print("Greater than:", a > b)
print("Not equal:", a != b)

# Logical operators
print("AND:", a > 5 and b < 5)
print("OR:", a < 5 or b < 5)
print("NOT:", not (a == b))

# Assignment operator
a += 2
print("After a += 2:", a)

# Membership operators
colors = ["red", "blue"]
print("'red' is in colors:", "red" in colors)
print("'green' is not in colors:", "green" not in colors)