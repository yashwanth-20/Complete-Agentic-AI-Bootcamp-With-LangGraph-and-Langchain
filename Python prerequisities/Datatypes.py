# Basic data types
age = 25                          # int: whole number
height = 5.7                      # float: decimal number
name = "Alice"                    # str: text
is_student = True                 # bool: True or False
colors = ["red", "green", "blue"] # list: ordered collection
coordinates = (10, 20)             # tuple: ordered, unchangeable collection
person = {"name": "Alice", "age": 25}  # dict: key-value pairs
unique_numbers = {1, 2, 3}        # set: collection of unique values
middle_name = None                 # NoneType: no value

# Display each value and its type
print(age, type(age))
print(height, type(height))
print(name, type(name))
print(is_student, type(is_student))
print(colors, type(colors))
print(coordinates, type(coordinates))
print(person, type(person))
print(unique_numbers, type(unique_numbers))
print(middle_name, type(middle_name))